// Regenerates skills/touch-grass/scripts/lib/logo.ts from the README logo: `node dev/logo.ts [columns]`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { inflateSync } from 'node:zlib';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const columns = Number(process.argv[2] ?? 40);

/** Decodes an 8-bit, non-interlaced RGB or RGBA PNG into RGB rows. */
function decode(file: Buffer): { width: number; height: number; rgb: (x: number, y: number) => [number, number, number] } {
  let offset = 8, width = 0, height = 0, channels = 0;
  const data: Buffer[] = [];
  while (offset < file.length) {
    const length = file.readUInt32BE(offset), type = file.toString('ascii', offset + 4, offset + 8), body = file.subarray(offset + 8, offset + 8 + length);
    if (type === 'IHDR') {
      width = body.readUInt32BE(0); height = body.readUInt32BE(4);
      if (body[8] !== 8 || body[12] !== 0 || (body[9] !== 2 && body[9] !== 6)) throw new Error('Only 8-bit, non-interlaced RGB or RGBA PNGs are supported.');
      channels = body[9] === 6 ? 4 : 3;
    }
    if (type === 'IDAT') data.push(body);
    offset += 12 + length;
  }
  const raw = inflateSync(Buffer.concat(data)), stride = width * channels, pixels = Buffer.alloc(height * stride);
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)]!, line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    for (let i = 0; i < stride; i++) {
      const left = i >= channels ? pixels[y * stride + i - channels]! : 0, up = y ? pixels[(y - 1) * stride + i]! : 0, corner = y && i >= channels ? pixels[(y - 1) * stride + i - channels]! : 0;
      const paeth = () => { const p = left + up - corner, a = Math.abs(p - left), b = Math.abs(p - up), c = Math.abs(p - corner); return a <= b && a <= c ? left : b <= c ? up : corner; };
      const predictor = [0, left, up, (left + up) >> 1, paeth()][filter]!;
      pixels[y * stride + i] = (line[i]! + predictor) & 0xff;
    }
  }
  return { width, height, rgb: (x, y) => [pixels[y * stride + x * channels]!, pixels[y * stride + x * channels + 1]!, pixels[y * stride + x * channels + 2]!] };
}

const image = decode(readFileSync(join(repo, '.github/assets/logo.png')));
const rows = Math.round((columns * image.height) / image.width / 2) * 2;
/** White, and the pale gray of the drop shadow and wind trail, which would read as a smudge on a dark terminal. */
const background = ([r, g, b]: number[]) => Math.min(r!, g!, b!) > 236 || (Math.min(r!, g!, b!) > 190 && Math.max(r!, g!, b!) - Math.min(r!, g!, b!) < 32);
const grid: string[] = [];
for (let y = 0; y < rows; y++) {
  let line = '';
  for (let x = 0; x < columns; x++) {
    const [x0, x1] = [Math.floor((x * image.width) / columns), Math.floor(((x + 1) * image.width) / columns)];
    const [y0, y1] = [Math.floor((y * image.height) / rows), Math.floor(((y + 1) * image.height) / rows)];
    const sum = [0, 0, 0];
    let solid = 0, total = 0;
    for (let sy = y0; sy < y1; sy++) for (let sx = x0; sx < x1; sx++) {
      total++;
      const pixel = image.rgb(sx, sy);
      if (background(pixel)) continue;
      solid++;
      pixel.forEach((value, channel) => { sum[channel]! += value; });
    }
    // Averaging only the logo's own pixels keeps edges from picking up a white halo on dark terminals.
    line += solid / total < 0.5 ? '......' : sum.map(value => Math.round(value / solid).toString(16).padStart(2, '0')).join('');
  }
  grid.push(line);
}
writeFileSync(join(repo, 'skills/touch-grass/scripts/lib/logo.ts'), `// Generated by \`node dev/logo.ts ${columns}\` from .github/assets/logo.png. Each row holds one RRGGBB per pixel, or ...... where the background shows.
export const logo: readonly string[] = [
${grid.map(line => `  '${line}',`).join('\n')}
];
`);
process.stdout.write(`${columns}x${rows} pixels, ${rows / 2} terminal rows\n`);
